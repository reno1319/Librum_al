type QueryValue = string | string[] | undefined;

/** The red box: our own message, the generic one for anything else, or nothing. */
export function pageErrorMessage(raw: QueryValue): string | null {
  if (raw === undefined || raw === "") return null;
  return typeof raw === "string" && PAGE_ERROR_MESSAGES.has(raw) ? raw : AUTH_GENERIC_ERROR_MESSAGE;
}

/** The green box: only our own message, never text from the address. */
export function pageSuccessMessage(raw: QueryValue): string | null {
  return typeof raw === "string" && PAGE_SUCCESS_MESSAGES.has(raw) ? raw : null;
}
